/* spictl.h -- the one client layer for rtl819x-spi's flash verbs.
 *
 * Every writer of /proc/rtl819x-spi verbs (cfgstore, brokerd, init's helper)
 * goes through this file and nothing else, so the lock, the one-write(2)-per-
 * verb rule, the staging appends, the /proc field reader and the guarded read
 * of /dev/mtd2ro each exist once.  The declarations between the PINNED markers
 * are SPEC-S144-U § 2's, copied; notes/self-update.md § 3.2 is the sequence the
 * config store builds from them (src/lib/cfgflash.c).
 *
 * ---------------------------------------------------------------------------
 * WHAT THE KERNEL SIDE IS, READ FROM IT
 * ---------------------------------------------------------------------------
 *
 *   READ kernel/linux-2.6.30/drivers/mtd/devices/rtl819x-spi.c's write_proc:
 *   a line of at most RLXFW_SPI_INST_LINE_MAX - 1 = 127 bytes, trailing \n and
 *   \r stripped, matched as `arm `<3 numbers>, `disarm`, `install...`,
 *   `erase...`, `img reset` (and the read-only verbs); the handler returns the
 *   byte count or the verb's -errno, so write(2)'s result IS the kernel's
 *   verdict.  /proc/rtl819x-spi-img appends to a RAM buffer under the driver's
 *   mutex and refuses an overflow whole (EFBIG), then EIO until `img reset`.
 *
 *   READ the vendor tree's fs/proc/generic.c:37: one read(2) of a read_proc_t
 *   file returns at most PROC_BLOCK_SIZE = PAGE_SIZE - 1024 = 3,072 bytes, and
 *   a second read(2) calls the handler AGAIN, so a page read in two reads is
 *   two generations of the counters stitched together.  /proc/rtl819x-spi's
 *   own budget (RTL819X_SPI_PROC_BUDGET, 3,584) is above that.  So fields are
 *   read from p->state, /proc/rtl819x-spi-inst -- n_writes, the install block
 *   and the counter's block, asserted at compile time to fit one read (the
 *   21:4x ruling of SPEC-S144-U § 2) -- and verbs still go to p->proc.
 *   spictl_field() reads it once and believes only complete lines, so even a
 *   node that outgrew its assert could only make a field ABSENT (-ENOENT),
 *   never give it a value from a cut line or from another generation.
 *
 *   flock(2) exists only in a kernel built with CONFIG_FILE_LOCKING; without
 *   it sys_flock is cond_syscall'd to -ENOSYS (READ kernel/sys_ni.c:128 in the
 *   vendor tree).  spictl_lock() then returns -ENOSYS at once, with no retry,
 *   and spictl_lock_why() names it, so every writer stops before its first
 *   verb with that reason rather than with a timeout.
 */
#ifndef RLXFW_SPICTL_H
#define RLXFW_SPICTL_H

#include <stddef.h>
#include <stdint.h>

/* ----- PINNED (SPEC-S144-U § 2) ------------------------------------------ */
struct spictl_paths {
	const char *proc;   /* "/proc/rtl819x-spi"      verbs are written here */
	const char *img;    /* "/proc/rtl819x-spi-img"  */
	const char *lock;   /* "/run/rlxfw-flash.lock"  */
	const char *flash;  /* "/dev/mtd2ro"            */
	const char *state;  /* "/proc/rtl819x-spi-inst" fields are read here (added 21:4x) */
};
/* 21:4x ruling: one read(2) of a /proc file returns at most PROC_BLOCK_SIZE =
 * PAGE_SIZE - 1024 = 3,072 bytes (fs/proc/generic.c:37; the driver sets *eof on
 * its first call), and the rest comes from a page regenerated by the next read.
 * The machine reader therefore reads a node that is never longer than 3,072:
 * /proc/rtl819x-spi-inst = n_writes + the install block + the ctr block. */
extern const struct spictl_paths spictl_dev;	/* the five device paths above */

/* flock(LOCK_EX|LOCK_NB) on p->lock, created 0600 if absent, retried every
 * 100 ms up to timeout_s; returns the fd (>= 0) or -ETIMEDOUT / -errno. */
int  spictl_lock(const struct spictl_paths *p, unsigned timeout_s);
void spictl_unlock(int fd);
/* One open(O_WRONLY) + ONE write(2) of the whole line (no '\n' needed) + close.
 * 0, or -errno as the write returned it (the kernel's refusal). */
int  spictl_verb(const struct spictl_paths *p, const char *line);
/* Staging: write(2)s of at most 4,096 bytes each to p->img, in order. 0 or -errno. */
int  spictl_stage(const struct spictl_paths *p, const void *buf, size_t len);
/* One read of p->state (it fits one read by construction), then the value of the line "key value":
 * 0 and a NUL-terminated copy; -ENOENT if no such line; -E2BIG if it does not fit. */
int  spictl_field(const struct spictl_paths *p, const char *key, char *out, size_t cap);
int  spictl_field_u32(const struct spictl_paths *p, const char *key, uint32_t *v);
/* pread of p->flash.  Refuses -EPERM, BEFORE any open, when [off, off+len)
 * overlaps [0, 0x10000) (the loader and H601) or wraps; -EINVAL unless off and
 * len are multiples of 4 (the driver's rule).  0 or -errno; a short read is -EIO. */
int  spictl_flash_read(const struct spictl_paths *p, uint32_t off, void *buf, size_t len);
/* ----- end PINNED -------------------------------------------------------- */

/* Additions.  Nothing above changes shape; these are what the implementation
 * and its host test (src/cfgstore/test_spictl.c) share. */

/* The most bytes one staging write(2) carries. */
#define SPICTL_STAGE_CHUNK	4096u
/* [0, SPICTL_GUARD_HI) is never read: the 64 KiB block that holds the loader,
 * H601, COMPDS and COMPCS (RLXFW_SPI_INST_FLOOR in the install header). */
#define SPICTL_GUARD_HI		0x00010000u
/* The bytes one spictl_field() read asks for (the buffer is one more). */
#define SPICTL_PAGE_MAX		4096
/* spictl_lock()'s retry step, and the longest wait it accepts. */
#define SPICTL_LOCK_STEP_MS	100u
#define SPICTL_LOCK_MAX_S	86400u
/* field_u32's widest value: ten digits and the NUL, with room to see an
 * eleventh digit as too long rather than as the end of the buffer. */
#define SPICTL_U32_TEXT		16

/* One line for a log, naming what a negative spictl_lock() return means:
 * -ENOSYS is the kernel without CONFIG_FILE_LOCKING, -ETIMEDOUT a lock held
 * past the timeout; anything else is "flock/open: errno N".  The string is
 * static and stays valid. */
const char *spictl_lock_why(int rc);

#endif /* RLXFW_SPICTL_H */
